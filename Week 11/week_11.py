import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/kaggle/Automobile_data.csv")

df

df.head()

df.tail()

df.shape

(df.isnull().sum())

df.duplicated().sum()

df.columns.tolist()

df.info()

df.describe(include="all")

df.select_dtypes(include="object").columns.tolist()

df.select_dtypes(include=np.number).columns.tolist()

df.replace(r"^\s*\?\s*$", np.nan, regex=True, inplace=True)

df.isnull().sum()

(df.isnull().mean() * 100).round(2)

numeric_columns = [
    "horsepower", "peak-rpm", "bore",
    "stroke", "price", "engine-size",
    "curb-weight", "city-mpg", "highway-mpg"
]

for col in numeric_columns:
    if col in df.columns:
        df[col] = pd.to_numeric(df[col], errors="coerce")

impute_columns = [
    "horsepower", "peak-rpm", "bore", "stroke", "price"
]

for col in impute_columns:
    if col in df.columns:
        df[col] = df.groupby("make")[col].transform(
            lambda group: group.fillna(group.median())
        )
        df[col] = df[col].fillna(df[col].median())

df[impute_columns].isnull().sum()

df["horsepower"] = df["horsepower"].round().astype("Int64")

for col in ["peak-rpm", "price", "bore", "stroke"]:
    df[col] = df[col].astype(float)
df[["horsepower", "peak-rpm", "price", "bore", "stroke"]].dtypes

df["power_to_weight_ratio"] = (
    df["horsepower"] / df["curb-weight"] * 1000
)
df[["make", "horsepower", "curb-weight",
          "power_to_weight_ratio"]].head()

df["combined_mpg"] = (
    df["city-mpg"] + df["highway-mpg"]
) / 2
df[["make", "city-mpg", "highway-mpg",
          "combined_mpg"]].head()

body_style_summary = df.groupby("body-style").agg(
    average_horsepower=("horsepower", "mean"),
    average_engine_size=("engine-size", "mean"),
    average_curb_weight=("curb-weight", "mean"),
    average_price=("price", "mean"),
    average_combined_mpg=("combined_mpg", "mean")
).round(2)
body_style_summary

engine_location_summary = df.groupby("engine-location").agg(
    average_horsepower=("horsepower", "mean"),
    average_engine_size=("engine-size", "mean"),
    average_curb_weight=("curb-weight", "mean"),
    average_price=("price", "mean")
).round(2)
(engine_location_summary)

df.to_csv("automobile_cleaned.csv", index=False)
