required = [
    "horsepower", "combined_mpg", "curb-weight", "fuel-type"
]

if all(col in df.columns for col in required):
    plot_df = df.dropna(subset=required).copy()
    weights = plot_df["curb-weight"]
    if weights.max() > weights.min():
        plot_df["bubble_size"] = (
            30 + 170 * (weights - weights.min()) /
            (weights.max() - weights.min())
        )
    else:
        plot_df["bubble_size"] = 80

    plt.figure(figsize=(10, 6))
    sns.scatterplot(
        data=plot_df,
        x="horsepower",
        y="combined_mpg",
        size="bubble_size",
        hue="fuel-type",
        sizes=(30, 200),
        alpha=0.7,
        legend="brief"
    )
    plt.title("Performance vs Fuel Efficiency")
    plt.xlabel("Horsepower")
    plt.ylabel("Combined MPG")
    plt.tight_layout()
    plt.show()

